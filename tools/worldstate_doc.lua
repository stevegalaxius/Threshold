-- Writes docs/world-state.md from data/notables.lua: every notable and
-- what their death changes. Run from the repo root: luajit tools/worldstate_doc.lua
package.path = "./?.lua;" .. package.path
local D = require("data.notables")
local function describe(e)
	if e.kind == "mul" then
		return ("%s x%.2f at %s%s"):format(e.target, e.by, e.where, e.sub and (" (" .. e.sub .. ")") or "")
	elseif e.kind == "beat" then return ("%s takes over %s's beat"):format(e.outlet, e.from)
	elseif e.kind == "stance" then return ("%s and %s become %s"):format(e.a, e.b, e.to)
	elseif e.kind == "shock" then return ("%s %+d%% at %s, fading over %dh"):format(e.item, math.floor(e.size * 100 + .5), e.where, math.floor(e.duration / 3600 + .5))
	elseif e.kind == "flag" then return "sets flag " .. e.flag end
	return e.kind
end
local out = {
	"# World state: notables and their consequences",
	"",
	"Generated by `tools/worldstate_doc.lua` from `data/notables.lua`. Do not edit by hand; edit the data and rerun.",
	"",
	"Every effect below is applied once, through `src/worldstate.lua`, when the notable dies or is captured, and never reverts. "
		.. "Each one is tagged with its source flag `notable.<id>`, which the F1 debug panel's \"Notables and world state\" section lists.",
	"",
	("Summits at %s every %dh; every %dth is a grand summit with every leader."):format(D.summit.station, D.summit.interval / 3600, D.summit.grandEvery),
	"",
}
local last
for _, n in ipairs(D.cast) do
	if n.faction ~= last then out[#out + 1] = "## " .. n.faction; out[#out + 1] = ""; last = n.faction end
	out[#out + 1] = ("### %s (%s)"):format(n.name, n.role)
	out[#out + 1] = ""
	out[#out + 1] = ("%s. Seat `%s`%s. Flag `notable.%s`. Player deed %d standing."):format(n.office:gsub("^%l", string.upper), n.seat,
		#(n.circuit or {}) > 0 and (", rides to `" .. table.concat(n.circuit, "`, `") .. "`") or ", travels only to summits", n.id, D.roles[n.role].deed)
	out[#out + 1] = ""
	for _, e in ipairs(D.consequences(n)) do out[#out + 1] = "- " .. describe(e) end
	out[#out + 1] = ""
end
local f = assert(io.open("docs/world-state.md", "w"))
f:write(table.concat(out, "\n"))
f:close()
print("wrote docs/world-state.md")
